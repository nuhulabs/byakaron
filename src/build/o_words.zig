//! Resync generator: Byakaron.db → the committed `src/AutoComplete/o_words.zon`.
//!
//!   o_words <Byakaron.db> <o_words.zon>
//!
//! The words that end in ও or ো, are attested in the Wikipedia corpus (at least
//! `min_frequency` times) and are another word plus that ও / ো: যদিও (যদি),
//! ভালো (ভাল), আমাদেরও (আমাদের). Avro's 2010 lexicon has few of them, so a final
//! typed `o` that one keeps would lose to the word where it vanished (see
//! `keepTypedO` in AutoComplete.zig). Run through `zig build o-words`.

const std = @import("std");
const sql = @import("sql");

/// কেনও and জন্মো are not words (0 and 1 in the corpus); every particle form a
/// sentence uses is far above this.
const min_frequency = 20;

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const io = init.io;

    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 3) {
        std.debug.print("usage: {s} <Byakaron.db> <o_words.zon>\n", .{args[0]});
        return error.InvalidArguments;
    }

    var db = try sql.open(init.gpa, io, args[1], .read_only);
    defer db.deinit();

    const query = try std.fmt.allocPrint(arena,
        \\SELECT d.word FROM dictionary d
        \\WHERE d.frequency >= {d} AND (d.word LIKE '%ও' OR d.word LIKE '%ো')
        \\  AND EXISTS (SELECT 1 FROM dictionary s WHERE s.word = substr(d.word, 1, length(d.word) - 1))
        \\ORDER BY d.word
    , .{min_frequency});
    // ORDER BY is SQLite's BINARY collation: byte order, which AutoComplete's
    // binary search needs.
    const words = try sql.column(arena, db, query);
    var zon: std.Io.Writer.Allocating = .init(arena);
    try zon.writer.writeAll(
        \\// Generated by `zig build o-words` (src/build/o_words.zig) from Byakaron.db.
        \\// Words that keep a final typed `o` as ও / ো: see `keepTypedO` in AutoComplete.zig.
        \\
    );
    try std.zon.stringify.serialize(words, .{}, &zon.writer);
    try zon.writer.writeByte('\n');
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = args[2], .data = zon.written() });
}
