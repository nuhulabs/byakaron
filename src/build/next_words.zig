//! Resync generator: Byakaron.db → the committed `src/ffi/next_words.zon`.
//!
//!   next_words <Byakaron.db> <next_words.zon>
//!
//! For the `max_words` most frequent words that start a bigram in the
//! Wikipedia corpus, the `per_word` words that most often follow them (each
//! seen at least `min_frequency` times): the next-word predictions a keyboard
//! without the database (iOS) shows after a word, like the system keyboard's
//! predictive bar. Byte-sorted by word for a binary search. Run through
//! `zig build gen -- next-words`.

const std = @import("std");
const sql = @import("sql");

const max_words = 3000;
const per_word = 3;
const min_frequency = 20;

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const io = init.io;

    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 3) {
        std.debug.print("usage: {s} <Byakaron.db> <next_words.zon>\n", .{args[0]});
        return error.InvalidArguments;
    }

    var db = try sql.open(init.gpa, io, args[1], .read_only);
    defer db.deinit();

    // The words, most frequent first, then their followers.
    const words_query = try std.fmt.allocPrint(arena,
        \\SELECT d.id, d.word FROM dictionary d
        \\WHERE d.id IN (SELECT DISTINCT w1_id FROM bigrams)
        \\ORDER BY d.frequency DESC LIMIT {d}
    , .{max_words});
    const rows = try db.all(arena, words_query, .{});

    const Entry = struct { word: []const u8, next: []const []const u8 };
    var entries: std.ArrayList(Entry) = .empty;
    for (rows) |row| {
        const id = row.int("id");
        const next_query = try std.fmt.allocPrint(arena,
            \\SELECT b.word FROM bigrams g JOIN dictionary b ON b.id = g.w2_id
            \\WHERE g.w1_id = {d} AND g.frequency >= {d}
            \\ORDER BY g.frequency DESC LIMIT {d}
        , .{ id, min_frequency, per_word });
        const next = try sql.column(arena, db, next_query);
        if (next.len == 0) continue;
        try entries.append(arena, .{ .word = row.text("word"), .next = next });
    }
    std.mem.sort(Entry, entries.items, {}, struct {
        fn less(_: void, a: Entry, b: Entry) bool {
            return std.mem.order(u8, a.word, b.word) == .lt;
        }
    }.less);

    var zon: std.Io.Writer.Allocating = .init(arena);
    try zon.writer.writeAll(
        \\// Generated by `zig build gen -- next-words` (src/build/next_words.zig) from Byakaron.db.
        \\// Next-word predictions: see `byakaron_next_words` in src/ffi/ffi.zig.
        \\
    );
    try std.zon.stringify.serialize(entries.items, .{}, &zon.writer);
    try zon.writer.writeByte('\n');
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = args[2], .data = zon.written() });
}
